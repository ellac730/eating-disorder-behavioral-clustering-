#helps avoid repetition for the 50-variable and 5-group model for elbow and silhouette analysis
def run_elbow_silhouette(X, title):
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X)

    inertias = []
    silhouette_scores = []
    K_range = range(2, 11)

    for k in K_range:
        kmeans = KMeans(n_clusters=k, random_state=42, n_init=20)
        labels = kmeans.fit_predict(X_scaled)
        inertias.append(kmeans.inertia_)
        silhouette_scores.append(silhouette_score(X_scaled, labels))

    plt.figure(figsize=(7, 4))
    plt.plot(list(K_range), inertias, marker="o")
    plt.title(f"Elbow Method for Choosing K: {title}")
    plt.xlabel("Number of clusters K")
    plt.ylabel("Inertia")
    plt.tight_layout()
    plt.show()

    plt.figure(figsize=(7, 4))
    plt.plot(list(K_range), silhouette_scores, marker="o")
    plt.title(f"Silhouette Score by K: {title}")
    plt.xlabel("Number of clusters K")
    plt.ylabel("Silhouette Score")
    plt.tight_layout()
    plt.show()

    results = pd.DataFrame({
        "K": list(K_range),
        "Inertia": inertias,
        "Silhouette Score": silhouette_scores
    })

    return results, X_scaled

