# Calculate Cramer's V
def cramers_v(contingency_table):

    chi2, p, dof, expected = chi2_contingency(
        contingency_table
    )

    n = contingency_table.to_numpy().sum()

    rows, columns = contingency_table.shape

    v = np.sqrt(
        chi2 /
        (
            n *
            min(rows - 1, columns - 1)
        )
    )

    return chi2, p, dof, v

